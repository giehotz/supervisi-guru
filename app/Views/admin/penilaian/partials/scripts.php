            cancelButtonColor: '#858796',
            confirmButtonText: '<i class="fas fa-eraser mr-1"></i> Ya, Kosongkan',
            cancelButtonText: 'Batal'
        }).then((result) => {
            if (result.isConfirmed) {
                catatanField.val('');
                catatanField.addClass('border-warning');
                setTimeout(function() {
                    catatanField.removeClass('border-warning');
                }, 800);
            }
        });
    });

    // Accordion icon toggle (chevron rotation)
    $('.accordion').on('show.bs.collapse', function (e) {
        $(e.target).prev('.card-header').find('.chevron-icon').removeClass('fa-chevron-right').addClass('fa-chevron-down');
