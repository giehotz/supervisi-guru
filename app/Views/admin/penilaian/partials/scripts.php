                                }
                            });
                        } else {
                            Swal.fire({
                                icon: 'error',
                                title: 'Gagal',
                                text: res.message || 'Gagal menghapus foto.'
                            });
                        }
                    },
                    error: function(xhr, status, error) {
                        Swal.fire({
                            icon: 'error',
                            title: 'Error',
                            text: 'Gagal menghapus foto: ' + error
                        });
                        if (xhr.responseJSON && xhr.responseJSON.token) {
                            updateCsrf(xhr.responseJSON.token);
                        }
                    }
                });
            }
        });
    });
});
