<script>
$(document).ready(function() {
    // CSRF Management
    var csrfName = '<?= csrf_token() ?>';
    var csrfHash = '<?= csrf_hash() ?>';

    function updateCsrf(newToken) {
        if (newToken) {
            csrfHash = newToken;
            $('input[name="' + csrfName + '"]').val(newToken);
        }
    }

    // Generator Catatan Kontekstual Dinamis berbasis Aspek & Skor
    function generateContextualNote(score, namaAspek, fokusPerilaku, kategori) {
        if (!score) return '';
        score = parseInt(score, 10);
        namaAspek = (namaAspek || 'aspek ini').trim();
        fokusPerilaku = (fokusPerilaku || '').trim();

        var isObservasi = (kategori === 'observasi_kelas_pmm') || (fokusPerilaku.length > 0);

        if (isObservasi) {
            // Gaya narasi observasi kelas / praktik pembelajaran di kelas
            var sasaran = fokusPerilaku ? fokusPerilaku : ('fokus ' + namaAspek);
            var aksi = sasaran.replace(/^guru\s+/i, '');
            switch (score) {
                case 4:
                    return 'Sangat Baik: Guru secara konsisten dan efektif ' + aksi + ' dengan suasana kelas yang sangat kondusif serta dampak nyata pada pemahaman peserta didik.';
                case 3:
                    return 'Baik: Guru telah ' + aksi + ' dengan baik dan teratur di kelas, bukti keterlaksanaan tampak jelas sesuai panduan observasi.';
                case 2:
                    return 'Cukup: Praktik ' + aksi + ' mulai tampak dilaksanakan, namun penerapannya belum konsisten atau masih memerlukan penguatan lebih lanjut.';
                case 1:
                    return 'Kurang: Praktik ' + aksi + ' belum tampak terlaksana secara nyata selama proses observasi pembelajaran di kelas.';
                default:
                    return '';
            }
        } else {
            // Gaya narasi dokumen perangkat ajar / administrasi / perencanaan
            switch (score) {
                case 4:
                    return 'Sangat Baik: Dokumen/bukti fisik ' + namaAspek + ' lengkap, mutakhir, terstruktur rapi, dan sepenuhnya sesuai dengan kriteria standar pembelajaran.';
                case 3:
                    return 'Baik: Dokumen ' + namaAspek + ' telah tersedia dan memenuhi standar dengan bukti dukung yang baik, hanya memerlukan sedikit penyesuaian minor.';
                case 2:
                    return 'Cukup: Dokumen ' + namaAspek + ' sudah ada namun belum lengkap atau belum dimutakhirkan, perlu perbaikan pada beberapa bagian pendukung.';
                case 1:
                    return 'Kurang: Dokumen/bukti fisik ' + namaAspek + ' belum tersedia atau belum disusun sesuai ketentuan standar.';
                default:
                    return '';
            }
        }
    }

    // Fungsi cek apakah catatan merupakan template bawaan sistem (agar tidak menimpa editan manual pengawas)
    function isAutoGeneratedNote(val) {
        if (!val || val.trim() === '') return true;
        var v = val.trim();
        var oldDefaults = [
            "Kurang, Tidak memiliki bukti dukung.",
            "Cukup, Memiliki bukti dukung, tetapi belum lengkap.",
            "Baik, Memiliki bukti dukung yang lengkap, namun belum sepenuhnya sesuai.",
            "Sangat Baik, Memiliki bukti dukung yang lengkap dan sepenuhnya sesuai."
        ];
        if (oldDefaults.indexOf(v) !== -1) return true;

        var prefixes = [
            "Sangat Baik: Dokumen/bukti fisik",
            "Baik: Dokumen",
            "Cukup: Dokumen",
            "Kurang: Dokumen/bukti fisik",
            "Sangat Baik: Guru secara konsisten",
            "Baik: Guru telah",
            "Cukup: Praktik",
            "Kurang: Praktik"
        ];
        for (var i = 0; i < prefixes.length; i++) {
            if (v.indexOf(prefixes[i]) === 0) return true;
        }
        return false;
    }

    // Auto-fill catatan kontekstual saat dropdown skor berubah
    $(document).on('change', '.skala-dropdown', function() {
        var dropdown = $(this);
        var score = dropdown.val();
        var namaAspek = dropdown.data('nama-aspek');
        var fokusPerilaku = dropdown.data('fokus-perilaku');
        var kategori = dropdown.data('kategori');
        var catatanField = dropdown.closest('tr').find('.catatan-field');

        if (score) {
            var currentVal = catatanField.val().trim();
            if (isAutoGeneratedNote(currentVal)) {
                var generatedNote = generateContextualNote(score, namaAspek, fokusPerilaku, kategori);
                catatanField.val(generatedNote);
            }
        }
    });

    // Tombol refresh catatan otomatis per baris
    $(document).on('click', '.btn-regen-catatan', function(e) {
        e.preventDefault();
        var tr = $(this).closest('tr');
        var dropdown = tr.find('.skala-dropdown');
        var score = dropdown.val();
        var namaAspek = dropdown.data('nama-aspek');
        var fokusPerilaku = dropdown.data('fokus-perilaku');
        var kategori = dropdown.data('kategori');
        var catatanField = tr.find('.catatan-field');

        if (!score) {
            Swal.fire({
                icon: 'info',
                title: 'Pilih Skor Dahulu',
                text: 'Silakan pilih skor (1 - 4) untuk aspek ini terlebih dahulu.',
                timer: 1500,
                showConfirmButton: false
            });
            return;
        }

        var note = generateContextualNote(score, namaAspek, fokusPerilaku, kategori);
        catatanField.val(note);
        catatanField.addClass('border-success');
        setTimeout(function() {
            catatanField.removeClass('border-success');
        }, 800);
    });

    // Bulk edit per accordion instrumen dengan catatan kontekstual unik
    $(document).on('click', '.bulk-edit-apply-btn', function() {
        var tabId = $(this).data('tab-id');
        var select = $('#bulk-skor-' + tabId);
        var score = select.val();

        if (!score) {
            Swal.fire({
                icon: 'warning',
                title: 'Perhatian',
                text: 'Silakan pilih skor terlebih dahulu pada dropdown!'
            });
            return;
        }

        var form = $('#form-' + tabId);
        form.find('.skala-dropdown').each(function() {
            var dropdown = $(this);
            dropdown.val(score);
            var namaAspek = dropdown.data('nama-aspek');
            var fokusPerilaku = dropdown.data('fokus-perilaku');
            var kategori = dropdown.data('kategori');
            var catatanField = dropdown.closest('tr').find('.catatan-field');
            
            var currentVal = catatanField.val().trim();
            if (isAutoGeneratedNote(currentVal)) {
                var generatedNote = generateContextualNote(score, namaAspek, fokusPerilaku, kategori);
                catatanField.val(generatedNote);
            }
        });

        Swal.fire({
            icon: 'success',
            title: 'Berhasil Diterapkan',
            text: 'Semua aspek pada instrumen ini telah diatur ke skor ' + score + ' dengan catatan kontekstual yang sesuai.',
            timer: 1500,
            showConfirmButton: false
        });
    });

    // Tombol Reset Catatan per Komponen dengan Konfirmasi
    $(document).on('click', '.btn-reset-bulk-catatan', function() {
        var tabId = $(this).data('tab-id');
        var form = $('#form-' + tabId);

        Swal.fire({
            title: 'Reset Semua Catatan?',
            text: 'Catatan pada instrumen ini akan dikembalikan ke catatan otomatis sesuai skor yang dipilih (atau dikosongkan jika belum memilih skor). Catatan manual Anda akan tertimpa.',
            icon: 'warning',
            showCancelButton: true,
            confirmButtonColor: '#e74a3b',
            cancelButtonColor: '#858796',
            confirmButtonText: '<i class="fas fa-undo mr-1"></i> Ya, Reset Catatan!',
            cancelButtonText: 'Batal'
        }).then((result) => {
            if (result.isConfirmed) {
                var resetCount = 0;
                form.find('.skala-dropdown').each(function() {
                    var dropdown = $(this);
                    var score = dropdown.val();
                    var namaAspek = dropdown.data('nama-aspek');
                    var fokusPerilaku = dropdown.data('fokus-perilaku');
                    var kategori = dropdown.data('kategori');
                    var catatanField = dropdown.closest('tr').find('.catatan-field');

                    if (score) {
                        var note = generateContextualNote(score, namaAspek, fokusPerilaku, kategori);
                        catatanField.val(note);
                    } else {
                        catatanField.val('');
                    }
                    resetCount++;
                });

                Swal.fire({
                    icon: 'success',
                    title: 'Catatan Berhasil Direset',
                    text: 'Seluruh catatan pada instrumen ini telah di-reset sesuai skor.',
                    timer: 1500,
                    showConfirmButton: false
                });
            }
        });
    });

    // Tombol Kosongkan Catatan per Aspek dengan Konfirmasi
    $(document).on('click', '.btn-clear-single-catatan', function(e) {
        e.preventDefault();
        var tr = $(this).closest('tr');
        var namaAspek = tr.find('.skala-dropdown').data('nama-aspek') || 'aspek ini';
        var catatanField = tr.find('.catatan-field');

        Swal.fire({
