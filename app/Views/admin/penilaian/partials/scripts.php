    $(document).on('click', '.btn-expand-all', function() {
        var target = $(this).data('target');
        $(target).find('.collapse').collapse('show');
    });
    $(document).on('click', '.btn-collapse-all', function() {
        var target = $(this).data('target');
        $(target).find('.collapse').collapse('hide');
    });

    // Helper: update dynamic badges for Step 1 and Step 2 counters
    function updateStepCounters() {
        var perangkatTotal = $('#accordionPerangkat .accordion-component-card').length;
        var perangkatDone = $('#accordionPerangkat .badge-status-item-done, #accordionPerangkat .badge-success').length;
        $('#badgeCountPerangkat').text(perangkatDone + ' / ' + perangkatTotal);

        var observasiTotal = $('#accordionObservasi .accordion-component-card').length;
        var observasiDone = $('#accordionObservasi .badge-status-item-done, #accordionObservasi .badge-success').length;
        $('#badgeCountObservasi').text(observasiDone + ' / ' + observasiTotal);
    }

    // Fungsi asynchronous untuk menyimpan semua form di dalam pane aktif
    async function saveFormsInPane(paneElement) {
        var forms = $(paneElement).find('.form-step-penilaian');
        var savedCount = 0;

        for (var i = 0; i < forms.length; i++) {
            var form = $(forms[i]);
            var tabId = form.find('input[name="jenis_penilaian_id"]').val();

            // Cek apakah form ini memiliki isian (skor atau rekomendasi)
            var hasData = false;
            form.find('.skala-dropdown').each(function() {
                if ($(this).val()) {
                    hasData = true;
                    return false;
                }
            });
            if (form.find('.rekomendasi-textarea').val() && form.find('.rekomendasi-textarea').val().trim() !== '') {
                hasData = true;
            }

            if (hasData) {
                form.find('input[name="' + csrfName + '"]').val(csrfHash);
                try {
                    var res = await $.ajax({
                        url: '<?= base_url($rolePrefix . '/penilaian/save') ?>',
                        method: 'POST',
                        data: form.serialize(),
                        dataType: 'json'
                    });

                    if (res.token) {
                        updateCsrf(res.token);
                    } else if (res.csrf_token) {
                        updateCsrf(res.csrf_token);
                    }

                    if (res.status === 'success') {
                        savedCount++;
                        $('.badge-status-' + tabId).html('<span class="badge badge-success badge-status-item-done"><i class="fas fa-check mr-1"></i>Tersimpan</span>');
                    }
                } catch (e) {
                    console.error('Error saving component ' + tabId, e);
                }
            }
        }

        return savedCount;
    }

    // Tombol Simpan Single Form per Accordion
    $(document).on('click', '.btn-save-single', function(e) {
        e.stopPropagation();
        var formId = $(this).data('form-id');
        $('#' + formId).trigger('submit');
    });

    // Handle AJAX form submission per accordion
    $('.form-step-penilaian').on('submit', function(e) {
        e.preventDefault();

        var form = $(this);
        var tabId = form.find('input[name="jenis_penilaian_id"]').val();
        var card = $('#card-component-' + tabId);
        var saveBtn = card.find('.btn-save-single');
        var originalBtnHtml = saveBtn.html();

        saveBtn.prop('disabled', true).html('<i class="fas fa-spinner fa-spin mr-1"></i> Menyimpan...');
        form.find('input[name="' + csrfName + '"]').val(csrfHash);

        $.ajax({
            url: '<?= base_url($rolePrefix . '/penilaian/save') ?>',
            method: 'POST',
            data: form.serialize(),
            dataType: 'json',
            success: function(res) {
                if (res.token) {
                    updateCsrf(res.token);
                } else if (res.csrf_token) {
                    updateCsrf(res.csrf_token);
                }

                if (res.status === 'success') {
                    Swal.fire({
                        icon: 'success',
                        title: 'Tersimpan!',
                        text: res.message || 'Penilaian komponen berhasil disimpan.',
                        timer: 1400,
                        showConfirmButton: false
                    });

                    $('.badge-status-' + tabId).html('<span class="badge badge-success badge-status-item-done"><i class="fas fa-check mr-1"></i>Tersimpan</span>');
                    updateStepCounters();
                } else {
                    Swal.fire({
                        icon: 'error',
                        title: 'Gagal Menyimpan',
                        text: res.message || 'Terjadi kesalahan saat menyimpan data.'
                    });
                }
            },
            error: function(xhr, status, error) {
                let msg = 'Terjadi kesalahan pada server: ' + error;
                if (xhr.responseJSON && xhr.responseJSON.message) {
                    msg = xhr.responseJSON.message;
                }
                Swal.fire({
                    icon: 'error',
                    title: 'Error Server',
                    text: msg
                });
                if (xhr.responseJSON && xhr.responseJSON.token) {
                    updateCsrf(xhr.responseJSON.token);
                }
            },
            complete: function() {
                saveBtn.prop('disabled', false).html(originalBtnHtml);
            }
        });
    });

    // Simpan Seluruh Form pada Step Aktif
    $(document).on('click', '.btn-save-step-group', async function() {
        var btn = $(this);
        var currentPane = btn.closest('.tab-pane');
        var originalHtml = btn.html();

        btn.prop('disabled', true).html('<i class="fas fa-spinner fa-spin mr-1"></i> Menyimpan Seluruh Tahap...');

        try {
            var count = await saveFormsInPane(currentPane);
            updateStepCounters();
            Swal.fire({
                icon: 'success',
                title: 'Tahap Berhasil Disimpan!',
                text: count > 0 ? (count + ' instrumen pada tahap ini berhasil disimpan ke database.') : 'Instrumen telah disimpan.',
                timer: 1500,
                showConfirmButton: false
            });
        } catch(err) {
            Swal.fire({
                icon: 'error',
                title: 'Gagal',
                text: 'Terjadi kesalahan saat menyimpan instrumen.'
            });
        } finally {
            btn.prop('disabled', false).html(originalHtml);
        }
    });

    // Navigasi Wizard Next dengan Auto-Save
    $(document).on('click', '.btn-wizard-next', async function() {
        var btn = $(this);
        var nextStepId = btn.data('next-step');
